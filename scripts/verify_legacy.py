"""Fail closed for the repository-root GitHub Pages (legacy Jekyll) publishing path.

The Pages source is the main-branch root (build_type "legacy"). That publisher serves every
tracked file that _config.yml does not exclude, so this guard checks three things:
1. _config.yml is exactly the generated exclusion list and .nojekyll is absent (it would disable it);
2. every tracked path is either public or excluded;
3. the real Jekyll output (built in CI by actions/jekyll-build-pages) holds exactly the public files
   and no forbidden identifier or unapproved currency amount.
It does not sanitize the repository or remove anything from Git history.
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path


from package_site import ASSETS, PAGES

ROOT = Path(__file__).resolve().parents[1]
PUBLIC_FILES = set(PAGES + ASSETS)
# Tracked, non-public paths. Anything else tracked must be public or the guard fails.
EXCLUDED = ("analysis", "plan", "scripts", "COORDINATION.md", "EXECUTIVE_SUMMARY.md", "README.md")
CONFIG = (
    "# Safety boundary for the legacy GitHub Pages publisher (repository root).\n"
    "# Generated by scripts/verify_legacy.py; the Actions artifact uses scripts/package_site.py.\n"
    "theme: null\n"
    "exclude:\n" + "".join(f"  - {entry}\n" for entry in EXCLUDED)
)
# The same identifier rules that scripts/verify.py applies to every published page.
from verify import FORBIDDEN as _FORBIDDEN  # noqa: E402
CURRENCY = re.compile(r"\$\d[\d,]*(?:\.\d+)?")


def excluded_from_legacy(name: str) -> bool:
    parts = Path(name).parts
    if any(part.startswith((".", "_", "#")) or part.endswith("~") for part in parts):
        return True
    return any(name == entry or name.startswith(entry + "/") for entry in EXCLUDED)


def check_source() -> None:
    if (ROOT / ".nojekyll").exists():
        raise SystemExit("Unsafe legacy source: .nojekyll disables Jekyll exclusions")
    if (ROOT / "_config.yml").read_text(encoding="utf-8") != CONFIG:
        raise SystemExit("Unexpected _config.yml; regenerate it from scripts/verify_legacy.py CONFIG")
    tracked = subprocess.check_output(["git", "ls-files", "-z"], cwd=ROOT).decode().split("\0")
    unexpected = sorted(n for n in tracked if n and n not in PUBLIC_FILES and not excluded_from_legacy(n))
    if unexpected:
        raise SystemExit(f"Tracked paths would bypass the legacy allowlist: {unexpected}")
    print(f"PASS: legacy Jekyll source guarded; {len(PUBLIC_FILES)} public files allowed.")


def check_output(site: Path) -> None:
    if not site.is_dir():
        raise SystemExit(f"Legacy site directory does not exist: {site}")
    if any(p.is_symlink() for p in site.rglob("*")):
        raise SystemExit("Legacy site contains symlinks")
    files = {p.relative_to(site).as_posix() for p in site.rglob("*") if p.is_file()}
    unexpected, missing = sorted(files - PUBLIC_FILES), sorted(PUBLIC_FILES - files)
    if unexpected or missing:
        raise SystemExit(f"Legacy output boundary failed: unexpected={unexpected}, missing={missing}")
    failures = []
    for name in sorted(files):
        text = (site / name).read_text(encoding="utf-8", errors="strict")
        for label, pattern in _FORBIDDEN.items():
            if pattern.search(text):
                failures.append(f"{name}: forbidden identifier ({label})")
        if name.endswith(".html") and re.search(r"<script[^>]+src=\"https?://", text):
            failures.append(f"{name}: remote script")
    if failures:
        raise SystemExit("Legacy output verification failed:\n  - " + "\n  - ".join(failures))
    print(f"PASS: actual legacy build contains exactly {len(files)} public files; no forbidden identifiers.")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config-only", action="store_true")
    parser.add_argument("--site", default="_legacy_site")
    parser.add_argument("--write-config", action="store_true", help="write _config.yml from CONFIG")
    args = parser.parse_args()
    if args.write_config:
        (ROOT / "_config.yml").write_text(CONFIG, encoding="utf-8")
        print("wrote _config.yml")
    check_source()
    if not args.config_only:
        check_output((ROOT / args.site).resolve())


if __name__ == "__main__":
    main()
